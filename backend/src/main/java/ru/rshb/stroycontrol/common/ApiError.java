package ru.rshb.stroycontrol.common;

import lombok.RequiredArgsConstructor;

/** Стабильные ошибки REST-контракта, общие для адаптеров и предметных операций. */
@RequiredArgsConstructor
public enum ApiError {
    /** Сдача отсутствует или относится к другому этапу. */
    ACCEPTANCE_NOT_FOUND(404, "Сдача не найдена или недоступна"),
    /** Версия сдачи или сводки уже изменилась. */
    STALE_ACCEPTANCE_VERSION(409, "Приёмка уже изменилась. Обновите данные"),
    /** Действие не соответствует текущей приёмке. */
    INVALID_ACCEPTANCE_STATE(409, "Проверьте готовность этапа и состояние приёмки"),
    /** Не все этапы приняты либо план пуст. */
    CONSTRUCTION_NOT_READY(409, "Для завершения примите все этапы строительства"),
    /** Стройка завершена владельцем; история доступна для чтения. */
    CONSTRUCTION_COMPLETED(409, "Строительство завершено. История доступна для чтения"),
    /** Для отправки необходимо подключить синтетическое кредитное дело. */
    BANK_CASE_REQUIRED(409, "Подключите демонстрационное кредитное дело"),
    /** Пакет уже изменил состояние. */
    STALE_BANK_VERSION(409, "Банковский пакет уже изменился. Обновите данные"),
    /** Нельзя отправить непринятый этап или дополнить завершённый банковский пакет. */
    INVALID_BANK_SUBMISSION_STATE(
            409, "Отправка недоступна в текущем состоянии банковского пакета"),
    /** Вложение отсутствует либо не принадлежит доступному проекту. */
    ATTACHMENT_NOT_FOUND(404, "Файл не найден или недоступен"),
    /** Загрузка ещё не завершена либо временный файл уже очищается. */
    ATTACHMENT_NOT_READY(409, "Файл ещё не готов. Повторите загрузку"),
    /** Размер файла превышает допустимый предел. */
    ATTACHMENT_TOO_LARGE(413, "Фото может занимать до 10 МиБ, PDF — до 20 МиБ"),
    /** Хранилище не подтвердило запись или чтение. */
    STORAGE_UNAVAILABLE(503, "Файловое хранилище временно недоступно. Повторите действие"),
    /** Некорректные поля, JSON или параметры маршрута. */
    VALIDATION_ERROR(400, "Проверьте введённые данные"),
    /** Конфликт уникального нормализованного email, включая гонку регистрации. */
    EMAIL_ALREADY_EXISTS(409, "Этот email уже зарегистрирован"),
    /** Общая ошибка неизвестного email и несовпадающего пароля. */
    INVALID_CREDENTIALS(401, "Неверный email или пароль"),
    /** Отсутствующая или завершённая сессия. */
    AUTH_REQUIRED(401, "Войдите в аккаунт"),
    /** Отклонение записи до проверки аутентификации и доступа. */
    INVALID_CSRF_TOKEN(403, "Обновите страницу и повторите действие"),
    /** Недостаточные права для операции над доступным объектом. */
    FORBIDDEN(403, "Действие недоступно для вашей роли"),
    /** Единая ошибка отсутствующей и скрытой от аккаунта карточки. */
    PROJECT_NOT_FOUND(404, "Карточка не найдена или недоступна"),
    /** По email нет аккаунта с ролью подрядчика. */
    CONTRACTOR_NOT_FOUND(422, "Подрядчик с таким email не зарегистрирован"),
    /** Попытка заменить уже назначенного подрядчика. */
    CONTRACTOR_ALREADY_ASSIGNED(409, "В карточке уже назначен другой подрядчик"),
    /** Формат тела не поддерживается JSON-операцией. */
    UNSUPPORTED_MEDIA_TYPE(415, "Для запроса требуется application/json"),
    /** Неверная дата или плановый финиш раньше старта. */
    INVALID_STAGE_DATES(400, "Проверьте даты: окончание не может быть раньше начала"),
    /** Этап отсутствует или не принадлежит указанной карточке. */
    STAGE_NOT_FOUND(404, "Этап не найден или недоступен"),
    /** Запись успели изменить после чтения клиентом. */
    STALE_STAGE_VERSION(409, "Этапы уже изменились. Обновите данные перед сохранением"),
    /** Нарушение последовательности работ или дат факта. */
    INVALID_STAGE_TRANSITION(409, "Сначала начните этап; завершение не может быть раньше начала"),

    /** Документ скрыт или отсутствует. */
    PROPOSAL_NOT_FOUND(404, "Предложение не найдено или недоступно"),
    /** Договор скрыт или отсутствует. */
    CONTRACT_NOT_FOUND(404, "Договор не найден или недоступен"),
    /** Конфликт версии заявки. */
    STALE_REQUEST_VERSION(409, "Заявка изменилась. Обновите данные"),
    /** Конфликт версии предложения. */
    STALE_PROPOSAL_VERSION(409, "Предложение изменилось. Обновите данные"),
    /** Конфликт версии договора. */
    STALE_CONTRACT_VERSION(409, "Договор изменился. Обновите данные"),
    /** Недопустимое действие над предложением. */
    INVALID_PROPOSAL_STATE(409, "Действие недоступно в текущем состоянии предложения"),
    /** Недопустимое действие над договором. */
    INVALID_CONTRACT_STATE(409, "Сначала согласуйте смету или проверьте состояние договора"),
    /** Заявку нельзя изменить. */
    REQUEST_LOCKED(409, "Отправленная заявка доступна только для чтения"),
    /** Подрядчик не выбран. */
    CONTRACTOR_REQUIRED(409, "Перед отправкой назначьте подрядчика"),
    /** План задаётся согласованным предложением. */
    APPROVED_PLAN_LOCKED(409, "План нового проекта составляется в предложении подрядчика"),
    /** Не согласован договор. */
    CONTRACT_REQUIRED(409, "Для начала работ согласуйте смету и договор подряда"),
    /** Демонстрационный банк временно недоступен. */
    BANK_DEMO_UNAVAILABLE(503, "Демонстрационный банк недоступен. Повторите позже"),
    /** Повторный ключ использован с другими данными. */
    IDEMPOTENCY_CONFLICT(409, "Ключ повтора уже использован с другими данными"),

    /** Запись ленты отсутствует или скрыта. */
    JOURNAL_ENTRY_NOT_FOUND(404, "Запись не найдена или недоступна"),
    /** Состояние этапа не допускает публикацию. */
    JOURNAL_STAGE_STATE(409, "Публикация этого типа недоступна в текущем состоянии этапа"),
    /** Ответ изменился после чтения. */
    STALE_JOURNAL_VERSION(409, "Запись уже изменилась. Обновите ленту"),
    /** У записи уже есть решение. */
    JOURNAL_ALREADY_RESOLVED(409, "Ответ уже сохранён. Для уточнения создайте новую запись"),
    /** Подготовка исходной карточки закрыта отказом. */
    PREPARATION_CLOSED(409, "Предложение отклонено. Подготовка в этой карточке закрыта"),
    /** Для исходной заявки уже создана копия. */
    REQUEST_ALREADY_REISSUED(409, "Копия уже создана. Откройте её по ссылке в карточке"),
    /** Адресат копии совпадает с прежним. */
    INVALID_REISSUE_CONTRACTOR(422, "Выберите другого подрядчика"),
    /** Заполните имя в личном профиле. */
    PROFILE_REQUIRED(409, "Заполните имя в личном профиле"),
    /** Профиль уже изменён. Обновите данные. */
    STALE_PROFILE_VERSION(409, "Профиль уже изменён. Обновите данные"),
    /** Организация отсутствует или недоступна. */
    ORGANIZATION_NOT_FOUND(404, "Организация отсутствует или недоступна"),
    /** Приглашение отсутствует или недоступно. */
    INVITATION_NOT_FOUND(404, "Приглашение отсутствует или недоступно"),
    /** Реквизиты или участник уже изменены. */
    STALE_ORGANIZATION_VERSION(409, "Реквизиты или участник уже изменены"),
    /** Команда уже изменена. Обновите данные. */
    STALE_TEAM_VERSION(409, "Команда уже изменена. Обновите данные"),
    /** Аккаунт уже состоит в организации или приглашение закрыто. */
    MEMBERSHIP_CONFLICT(409, "Аккаунт уже состоит в организации или приглашение закрыто"),
    /** Организация с таким ИНН уже зарегистрирована. */
    ORGANIZATION_ALREADY_EXISTS(409, "Организация с таким ИНН уже зарегистрирована"),
    /** Выберите действующего сотрудника своей организации. */
    INVALID_TEAM_MEMBER(422, "Выберите действующего сотрудника своей организации"),
    /** Подрядчик должен заполнить профиль организации; укажите email руководителя. */
    CONTRACTOR_PROFILE_REQUIRED(
            422, "Подрядчик должен заполнить профиль организации; укажите email руководителя");

    final int status;
    final String title;
}
