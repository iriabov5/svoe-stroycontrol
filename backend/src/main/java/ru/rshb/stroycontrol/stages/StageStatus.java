package ru.rshb.stroycontrol.stages;

/** Факт выполнения работ; состояние приёмки будет в отдельном модуле. */
public enum StageStatus {
    /** Работы ещё не начаты. */
    PLANNED,
    /** Начало зафиксировано, завершения пока нет. */
    IN_PROGRESS,
    /** Подрядчик завершил работы, что не означает приёмку заказчиком. */
    WORK_COMPLETED
}
